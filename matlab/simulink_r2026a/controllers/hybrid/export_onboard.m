function export_onboard()
%EXPORT_ONBOARD Write the on-board (ESP32) copy of the hybrid controller's design, and replay vectors.
%   export_onboard()
%
%   One design, two copies. The knobs live in ctrl_hybrid_design.m only. This writes
%     firmware/include/onboard_design.h    every number the firmware controller uses (K from dlqr,
%                                          swing-up knobs, supervisor guards, estimator, plant constants)
%     firmware/test/onboard_replay_<scenario>.csv   controller input y and the duty Simulink commanded
%   for the 'swingup' and 'push' scenarios (realistic sensors and firmware, nominal plant).
%   firmware/test/native_onboard.cpp feeds the same inputs to the C++ copy and requires the same duty.
%   Re-run after any change to ctrl_hybrid_design.m, then rebuild and re-flash the firmware.
here = fileparts(mfilename('fullpath'));
fwdir = fullfile(here, '..', '..', '..', '..', 'firmware');
cfg = harness_config('realistic', 'Model', '20261120');   % replays on the rig as re-identified (the design model)
P = ctrl_hybrid_design(cfg);
assert(P.stab == 3, 'export_onboard: the on-board copy implements the LQR stabilizer (ctrlP.stab = 3)');

L = {};
add = @(name, v, note) sprintf('constexpr double %s = %.17g;%s', name, v, note);
L{end+1} = '// GENERATED by controllers/hybrid/export_onboard.m (matlab/simulink_r2026a or _r2023a) from ctrl_hybrid_design.m.';
L{end+1} = '// Do not edit: change the design file and re-run export_onboard. Units: rad, rad/s, s, A, duty.';
L{end+1} = sprintf('// Generated %s.', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
L{end+1} = '#pragma once';
L{end+1} = 'namespace fw { namespace design {';
L{end+1} = add('Ts', P.Ts, '              // controller period');
L{end+1} = add('velFc', P.est.vel_fc, '           // velocity filter cut-off [Hz]');
L{end+1} = sprintf('constexpr double K[4] = {%.17g, %.17g, %.17g, %.17g};  // duty = -K (x - [r 0 0 0])', P.lqr.K);
L{end+1} = add('fricGain', P.fric.gain, '');
L{end+1} = add('fricBand', P.fric.band, '');
L{end+1} = add('fricDutyPos', P.fric.duty(1), '');
L{end+1} = add('fricDutyNeg', P.fric.duty(2), '');
L{end+1} = add('fricStick', P.fric.stick, '        // 1.9: breakaway part of the balance compensation');
L{end+1} = add('catchTh1', P.sup.catch_th1, '');
L{end+1} = add('catchW1', P.sup.catch_w1, '');
L{end+1} = add('exitTh1', P.sup.exit_th1, '');
L{end+1} = add('safeTh0', P.sup.safe_th0, '');
L{end+1} = add('rearm', P.sup.rearm, '');
s = P.swing;
for f = {'E0', 'k_E', 'a_push', 'wc', 'zc', 'a_kick', 'kick_E', 'w_sign', 'w_fric', 'i_max', 'u_max', ...
         'stick_gain', 'w_stick', 'a_stick'}
    L{end+1} = add(['sw_' f{1}], s.(f{1}), ''); %#ok<AGROW>
end
L{end+1} = add('estKind', P.est.kind, '        // 1.12: 0 filtered differences, 1 model observer, 2 its fallback');
L{end+1} = add('estLag', P.est.nd*P.Ts, '       // lag the observer compensates [s] (nd ticks at the design period)');
L{end+1} = add('estFab', P.est.f_ab, '');
L{end+1} = add('estFtrk', P.est.f_trk, '');
L{end+1} = add('estSub', P.est.sub, '           // RK4 substeps per tick in the observer model');
m = P.plant;
for f = {'Jp', 'G', 'Ja', 'Beq', 'tcp', 'tcn', 'Rm', 'Kb', 'Vs', 'tsp', 'tsn', 'h', 'b1', 'tp', 'eps', 'eps1', 'stick_band', 'stick_T'}
    L{end+1} = add(['pl_' f{1}], m.(f{1}), ''); %#ok<AGROW>
end
L{end+1} = 'constexpr int modelArmSign = 1;    // device profile signs the identified model was fitted with';
L{end+1} = 'constexpr int modelPendSign = -1;  // (data/estimation/model_20261115: pend_sign -1, recordings armSign +1)';
L{end+1} = '}}';
hfile = fullfile(fwdir, 'include', 'onboard_design.h');
fid = fopen(hfile, 'w'); fprintf(fid, '%s\n', L{:}); fclose(fid);
fprintf('wrote %s\n', hfile);

w = warning('off', 'all'); c = onCleanup(@() warning(w));
for sc = {'swingup', 'push'}
    R = run_sim('ctrl_hybrid.slx', sc{1}, 'Cfg', cfg);
    y = R.y; n = min([size(y, 1), numel(R.u), numel(R.r), numel(R.mode)]);
    T = [R.t(1:n), y(1:n, 1), y(1:n, 2), R.r(1:n), R.u(1:n), R.mode(1:n)];
    f = fullfile(fwdir, 'test', ['onboard_replay_' sc{1} '.csv']);
    fid = fopen(f, 'w'); fprintf(fid, 't,th0,th1,r,duty,mode\n');
    fprintf(fid, '%.6f,%.17g,%.17g,%.17g,%.17g,%d\n', T'); fclose(fid);
    fprintf('wrote %s (%d rows, pass %d, catch %.2f s)\n', f, n, R.pass, R.metrics.t_capture);
end
end
