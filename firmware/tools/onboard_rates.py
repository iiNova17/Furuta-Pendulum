"""Write firmware/include/onboard_rates.h: the LQR gain for every onboard controller period.

The LQR is the design of matlab/harness/controllers/hybrid/ctrl_hybrid_design.m (sim-harness branch):
    sysd = c2d(ss(A_up, Bd_up, eye(4), 0), Ts);  K = dlqr(sysd.A, sysd.B, Q, R)
with Q = diag(1./[30 deg, 8 deg, 20, 30].^2) and R = 1/0.10^2, and A_up / Bd_up of matlab/model/furuta_params.m
(report eq. 104, duty input). Only the sample time Ts changes here; the weights are the design file's.
Check: the 4 ms gain must equal design::K in onboard_design.h (export_onboard.m) to round-off; the script
refuses to write otherwise. Re-run after a change of Q, R or the model:

    python firmware/tools/onboard_rates.py
"""
import math
import re
import sys
from pathlib import Path
import numpy as np
from scipy.linalg import expm, solve_discrete_are

HERE = Path(__file__).resolve().parent
INCLUDE = HERE.parent / 'include'
PERIODS = (0.001, 0.002, 0.004)          # supported controller periods [s]

A_up = np.array([[0, 0, 1, 0], [0, 0, 0, 1], [0, -5.812080219, -28.92465458, 0.02422587031],
                 [0, 162.7379816, 31.40924044, -0.6783232662]])
Bd_up = np.array([[0], [0], [646.8495011], [-702.4129348]])
Q = np.diag(1 / np.array([math.radians(30), math.radians(8), 20, 30]) ** 2)
R = np.array([[1 / 0.10 ** 2]])


def c2d(A, B, Ts):
    """Zero-order hold, as MATLAB c2d."""
    n, m = A.shape[0], B.shape[1]
    M = np.zeros((n + m, n + m)); M[:n, :n] = A; M[:n, n:] = B
    E = expm(M * Ts)
    return E[:n, :n], E[:n, n:]


def dlqr(A, B, Q, R):
    P = solve_discrete_are(A, B, Q, R)
    return np.linalg.solve(R + B.T @ P @ B, B.T @ P @ A)


def gains():
    out = {}
    for Ts in PERIODS:
        Ad, Bd = c2d(A_up, Bd_up, Ts)
        K = dlqr(Ad, Bd, Q, R).ravel()
        poles = np.linalg.eigvals(Ad - Bd @ K.reshape(1, 4))
        out[Ts] = (K, poles)
    return out


def design_K():
    text = (INCLUDE / 'onboard_design.h').read_text(encoding='utf-8')
    m = re.search(r'K\[4\]\s*=\s*\{([^}]*)\}', text)
    return np.array([float(v) for v in m.group(1).split(',')])


def main():
    g = gains(); ref = design_K()
    err = np.max(np.abs(g[0.004][0] - ref) / np.abs(ref))
    print(f'4 ms gain vs onboard_design.h: max relative difference {err:.2e}')
    if err > 1e-6:
        sys.exit('The 4 ms gain does not reproduce the design file: Q, R or the model differ. Not written.')
    lines = ['// GENERATED by firmware/tools/onboard_rates.py. Do not edit: re-run the script.',
             '// LQR gain of ctrl_hybrid_design.m (same Q, R and model) for every supported controller period;',
             f'// the 4 ms row reproduces design::K of onboard_design.h (relative difference {err:.1e}).',
             '#pragma once', 'namespace fw { namespace rates {',
             f'constexpr int count = {len(PERIODS)};',
             'constexpr double Ts[count] = {' + ', '.join(f'{t:.3f}' for t in PERIODS) + '};',
             'constexpr double K[count][4] = {']
    for Ts in PERIODS:
        K, poles = g[Ts]
        lines.append('  {' + ', '.join(f'{k:.17g}' for k in K) + f'}},   // {Ts * 1e3:g} ms, |z| max {np.max(np.abs(poles)):.6f}')
    lines += ['};', '}}', '']
    (INCLUDE / 'onboard_rates.h').write_text('\n'.join(lines), encoding='utf-8')
    for Ts in PERIODS:
        K, poles = g[Ts]
        s = np.log(poles.astype(complex)) / Ts
        print(f'{Ts * 1e3:g} ms: K = {np.array2string(K, precision=5)}, closed-loop poles s = '
              + ', '.join(f'{v.real:.2f}{v.imag:+.2f}j' for v in sorted(s, key=lambda v: v.real)))
    print('wrote', INCLUDE / 'onboard_rates.h')


if __name__ == '__main__':
    main()
